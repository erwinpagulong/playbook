"""Tests for the loopback daemon, scheduler, and CLI helper (Task 9).

Everything here runs offline: the daemon fixture binds 127.0.0.1 on an
ephemeral port (port 0) in a daemon thread and is talked to through a
small urllib client; generation is monkeypatched wherever a test would
otherwise reach the network; the CLI wrappers run as subprocesses against
the fixture server. The autouse ``xdg_isolation`` fixture points
``XDG_CONFIG_HOME`` / ``XDG_DATA_HOME`` at ``tmp_path`` so no test can
touch the user's real config or report store, and drops ``OPENAI_API_KEY``
so daemon startup never triggers a live generation.
"""

