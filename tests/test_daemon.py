def test_scheduler_loop_ticks_on_interval_then_stops(server, monkeypatch):
    generated = []
    monkeypatch.setattr(
        daemon.generate,
        "generate_report",
        lambda coin, config, data_dir: (
            generated.append(coin),
            {"report": None, "error": None},
        )[1],
    )
    server.config["interval_minutes"] = 15
    waits = []

    def fake_wait(seconds):
        waits.append(seconds)
        return len(waits) > 1  # let one interval elapse, then stop

