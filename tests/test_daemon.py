#: Loopback-only opener: proxy env vars must never intercept these calls.
OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}))

#: The wrapper scripts under test. ``__MODULE__`` becomes ``cli`` /
#: ``daemon``; the same text is written to the repo's gitignored ``bin/``
#: (install.sh, Task 12) — ``test_repo_wrappers_match_the_tested_script``
#: fails if the two ever drift.
WRAPPER_SCRIPT = """#!/bin/sh
# Crypto Playbook __MODULE__ wrapper (generated by install.sh; gitignored).
# Resolves its own directory so it works from any cwd, puts the plugin
# root on PYTHONPATH, and prefers the plugin's own .venv interpreter.
set -eu
self=$(readlink -f -- "$0")
root=$(dirname -- "$(dirname -- "$self")")
export PYTHONPATH="$root${PYTHONPATH:+:$PYTHONPATH}"
py="$root/.venv/bin/python"
[ -x "$py" ] || py=python3
exec "$py" -B -m engine.__MODULE__ "$@"
"""


def write_wrapper(path: Path, module: str) -> None:
    """Write the wrapper script for ``engine.<module>`` and chmod +x it."""
    path.write_text(WRAPPER_SCRIPT.replace("__MODULE__", module), encoding="utf-8")
    path.chmod(0o755)


class Response:
    """Minimal urllib-backed response: status code plus ``.json()``."""

    def __init__(self, status: int, body: bytes):
        self.status = status
        self.body = body

    def json(self):
        return json.loads(self.body.decode("utf-8"))


class Client:
    """GET/POST client for the fixture server; JSON in, JSON out."""

    def __init__(self, base: str):
        self.base = base

    def get(self, path: str) -> Response:
        return self._send(urllib.request.Request(self.base + path, method="GET"))

    def post(self, path: str, payload=None, **kwargs) -> Response:
        if payload is None:
            payload = kwargs.get("json")
        body = json.dumps(payload).encode("utf-8") if payload is not None else b""
        request = urllib.request.Request(
            self.base + path,
            data=body,
            method="POST",
            headers={"Content-Type": "application/json"},
        )
        return self._send(request)

    @staticmethod
    def _send(request) -> Response:
        # Read on every call: a test may start a second daemon in the same XDG
        # sandbox, which rotates the token file.
        token = daemon_token_path().read_text(encoding="utf-8").strip()
        request.add_header("Authorization", f"Bearer {token}")
        try:
            with OPENER.open(request, timeout=10) as response:
                return Response(response.status, response.read())
        except urllib.error.HTTPError as error:  # 4xx/5xx still carry JSON
            return Response(error.code, error.read())


