def test_playbookd_serves_seeded_api_on_ephemeral_port(BIN, tmp_path):
    env = os.environ.copy()
    env.pop("PYTHONPATH", None)
    env.pop("OPENAI_API_KEY", None)  # no key -> no startup generation
    env["XDG_DATA_HOME"] = str(tmp_path / "xdata")
    env["XDG_CONFIG_HOME"] = str(tmp_path / "xcfg")
    process = subprocess.Popen(
        [str(BIN / "playbookd"), "-port", "0"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        env=env,
        cwd=str(tmp_path),
    )
    first_line: list[str] = []
    reader = threading.Thread(
        target=lambda: first_line.append(process.stdout.readline()), daemon=True
    )
    reader.start()
    reader.join(timeout=15)
    try:
        if not first_line or not first_line[0]:
            process.terminate()
            process.wait(timeout=10)
            pytest.fail(
                f"playbookd printed no startup line; stderr={process.stderr.read()!r}"
            )
        match = re.search(r"listening on 127\.0\.0\.1:(\d+)", first_line[0])
        assert match, f"unexpected startup line: {first_line[0]!r}"
        base = f"http://127.0.0.1:{match.group(1)}"
        # The child daemon has its own XDG_DATA_HOME, distinct from the test's.
        token_file = Path(env["XDG_DATA_HOME"]) / "crypto-playbook" / "daemon.token"
        token = token_file.read_text(encoding="utf-8").strip()
        auth_headers = {"Authorization": f"Bearer {token}"}
        with OPENER.open(
            urllib.request.Request(base + "/api/health", headers=auth_headers), timeout=10
        ) as response:
            assert json.loads(response.read()) == {"status": "ok"}
        with OPENER.open(
            urllib.request.Request(base + "/api/latest", headers=auth_headers), timeout=10
        ) as response:
            latest = json.loads(response.read())
        # startup seeded the samples and served them without any network call
        assert latest["available"] is True
        assert latest["report"]["sample"] is True
    finally:
        process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=10)


